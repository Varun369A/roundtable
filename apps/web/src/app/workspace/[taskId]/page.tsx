'use client'

import { useEffect, useState, useCallback, useRef, use } from 'react'
import { useRouter } from 'next/navigation'
import Link from 'next/link'
import { apiFetch } from '@/lib/api'
import FileTree from '@/components/workspace/FileTree'
import CodeViewer from '@/components/workspace/CodeViewer'
import { EnvVarsPanel } from '@/components/workspace/EnvVarsPanel'
import { EditChatPanel } from '@/components/workspace/EditChatPanel'
import { EditPlanCard } from '@/components/workspace/EditPlanCard'
import { DiffViewer } from '@/components/workspace/DiffViewer'

interface CodeFile {
  path:     string
  content:  string
  language: string
}

interface CodeProject {
  id:       string
  taskId:   string
  name:     string
  files:    CodeFile[]
  status:   'ASSEMBLING' | 'READY' | 'FAILED' | 'COMPLETE' | 'DRAFT'
  repoUrl:  string | null
  pushedAt: string | null
}

interface GitHubConnection {
  login:     string
  avatarUrl: string | null
}

interface EditPlan {
  sessionId:   string
  explanation: string
  files:       Array<{ path: string; description: string }>
}

interface AppliedFile {
  path:       string
  fileIndex:  number
  totalFiles: number
}

export default function WorkspacePage({ params }: { params: Promise<{ taskId: string }> }) {
  const { taskId } = use(params)
  const router  = useRouter()

  const [project,    setProject]    = useState<CodeProject | null>(null)
  const [loading,    setLoading]    = useState(true)
  const [selected,   setSelected]   = useState<CodeFile | null>(null)
  const [ghConn,     setGhConn]     = useState<GitHubConnection | null>(null)
  const [pushing,    setPushing]    = useState(false)
  const [pushError,  setPushError]  = useState('')
  const [repoInput,  setRepoInput]  = useState('')
  const [showPush,   setShowPush]   = useState(false)
  const [assembling, setAssembling] = useState(false)
  const [activeTab,  setActiveTab]  = useState<'code' | 'env' | 'edit'>('code')

  // Edit mode state
  const [editEnabled,   setEditEnabled]   = useState(false)
  const [pendingPlan,   setPendingPlan]   = useState<EditPlan | null>(null)
  const [isApplying,    setIsApplying]    = useState(false)
  const [appliedFiles,  setAppliedFiles]  = useState<AppliedFile[]>([])
  const [applyTotal,    setApplyTotal]    = useState(0)
  const [activeSession, setActiveSession] = useState<string | null>(null)

  const sseRef = useRef<EventSource | null>(null)

  const load = useCallback(async () => {
    const [projRes, ghRes] = await Promise.all([
      apiFetch<{ project: CodeProject | null }>(`/api/v1/code-projects/${taskId}`),
      apiFetch<{ connection: GitHubConnection | null }>('/api/v1/github/connection'),
    ])
    if (!projRes.success) { router.push('/dashboard'); return }
    if (projRes.data?.project) {
      setProject(projRes.data.project)
      if (projRes.data.project.files.length > 0 && !selected) {
        setSelected(projRes.data.project.files[0])
      }
      // If project is COMPLETE/DRAFT (generated by engine), enable edit mode
      const s = projRes.data.project.status
      if (s === 'COMPLETE' || s === 'DRAFT' || s === 'READY') {
        setEditEnabled(true)
      }
    }
    if (ghRes.success) setGhConn(ghRes.data?.connection ?? null)
    setLoading(false)
  }, [taskId, router, selected])

  useEffect(() => {
    load()
  }, [load])

  // Poll while assembling
  useEffect(() => {
    if (project?.status !== 'ASSEMBLING') return
    const interval = setInterval(load, 3000)
    return () => clearInterval(interval)
  }, [project?.status, load])

  // SSE subscription for edit events
  useEffect(() => {
    if (!editEnabled) return
    const token = typeof window !== 'undefined' ? localStorage.getItem('accessToken') : null
    if (!token) return

    const apiUrl = process.env.NEXT_PUBLIC_API_URL || 'http://localhost:3001'
    const es = new EventSource(`${apiUrl}/api/v1/stream/task/${taskId}?token=${token}`)
    sseRef.current = es

    es.addEventListener('edit_mode_enabled', () => {
      setEditEnabled(true)
    })

    es.addEventListener('edit_plan_ready', (e) => {
      const data = JSON.parse(e.data)
      setPendingPlan({
        sessionId:   data.sessionId,
        explanation: data.explanation,
        files:       data.files ?? [],
      })
      // Switch to edit tab automatically so user sees the plan
      setActiveTab('edit')
    })

    es.addEventListener('edit_applying', (e) => {
      const data = JSON.parse(e.data)
      setIsApplying(true)
      setAppliedFiles([])
      setApplyTotal(data.totalFiles ?? 0)
      setPendingPlan(null)
    })

    es.addEventListener('edit_file_completed', (e) => {
      const data = JSON.parse(e.data)
      setAppliedFiles((prev) => [
        ...prev,
        { path: data.filePath, fileIndex: data.fileIndex, totalFiles: data.totalFiles },
      ])
    })

    es.addEventListener('edit_completed', () => {
      setIsApplying(false)
      setActiveSession(null)
      // Reload project files from DB to reflect the edits
      load()
    })

    es.addEventListener('edit_failed', (e) => {
      const data = JSON.parse(e.data)
      setIsApplying(false)
      setActiveSession(null)
      console.error('[Edit] edit_failed:', data.error)
    })

    return () => {
      es.close()
      sseRef.current = null
    }
  }, [editEnabled, taskId, load])

  async function triggerAssemble() {
    setAssembling(true)
    const res = await apiFetch(`/api/v1/code-projects/${taskId}/assemble`, { method: 'POST' })
    if (res.success) {
      setProject((p) => p ? { ...p, status: 'ASSEMBLING' } : null)
    }
    setAssembling(false)
  }

  async function downloadZip() {
    const token = typeof window !== 'undefined' ? localStorage.getItem('accessToken') : null
    const a = document.createElement('a')
    a.href = `/api/v1/code-projects/${taskId}/download`
    if (token) a.href += `?token=${token}`
    a.download = `${project?.name ?? 'project'}.zip`
    a.click()
  }

  async function pushToGitHub() {
    setPushError('')
    setPushing(true)
    const res = await apiFetch<{ repoUrl: string; repoName: string }>(
      `/api/v1/code-projects/${taskId}/push`,
      {
        method: 'POST',
        body:   JSON.stringify({ repoName: repoInput || undefined, isPrivate: false }),
      }
    )
    setPushing(false)
    if (res.success && res.data) {
      setProject((p) => p ? { ...p, repoUrl: res.data!.repoUrl, pushedAt: new Date().toISOString() } : null)
      setShowPush(false)
    } else {
      setPushError(res.error?.message ?? 'Push failed')
    }
  }

  function handleEditPlanApproved() {
    setPendingPlan(null)
    setIsApplying(true)
  }

  function handleEditPlanRejected() {
    setPendingPlan(null)
    setActiveSession(null)
  }

  if (loading) {
    return (
      <div className="min-h-screen bg-slate-50 flex items-center justify-center">
        <div className="flex gap-2">
          {[0, 150, 300].map((d) => (
            <div key={d} className="w-2.5 h-2.5 rounded-full bg-indigo-500 animate-bounce" style={{ animationDelay: `${d}ms` }} />
          ))}
        </div>
      </div>
    )
  }

  if (!project) {
    return (
      <div className="min-h-screen bg-slate-50 flex flex-col items-center justify-center gap-6 text-center px-4">
        <p className="text-4xl">💻</p>
        <div>
          <h1 className="text-xl font-semibold text-slate-900 mb-2">No workspace yet</h1>
          <p className="text-slate-500 text-sm max-w-sm">
            The code workspace is assembled automatically when a development task completes. You can also trigger it manually.
          </p>
        </div>
        <div className="flex gap-3">
          <button
            onClick={triggerAssemble}
            disabled={assembling}
            className="px-4 py-2 rounded-xl bg-indigo-600 hover:bg-indigo-500 text-white text-sm font-medium transition-colors disabled:opacity-50"
          >
            {assembling ? 'Assembling…' : 'Assemble Workspace'}
          </button>
          <Link href={`/roundtable/${taskId}`} className="px-4 py-2 rounded-xl border border-slate-300 hover:border-slate-400 text-slate-500 text-sm transition-colors">
            Back to task
          </Link>
        </div>
      </div>
    )
  }

  if (project.status === 'ASSEMBLING') {
    return (
      <div className="min-h-screen bg-slate-50 flex flex-col items-center justify-center gap-4 text-center">
        <div className="flex gap-2">
          {[0, 150, 300].map((d) => (
            <div key={d} className="w-2.5 h-2.5 rounded-full bg-indigo-500 animate-bounce" style={{ animationDelay: `${d}ms` }} />
          ))}
        </div>
        <p className="text-slate-500 text-sm">Assembling your code workspace…</p>
        <p className="text-slate-400 text-xs">AI output is being parsed into a file structure</p>
      </div>
    )
  }

  if (project.status === 'FAILED') {
    return (
      <div className="min-h-screen bg-slate-50 flex flex-col items-center justify-center gap-6 text-center px-4">
        <p className="text-4xl">⚠️</p>
        <div>
          <h1 className="text-xl font-semibold text-slate-900 mb-2">Assembly failed</h1>
          <p className="text-slate-500 text-sm max-w-sm">
            The workspace couldn't be assembled from the task output. This usually means the AI didn't output structured file content.
          </p>
        </div>
        <button
          onClick={triggerAssemble}
          disabled={assembling}
          className="px-4 py-2 rounded-xl bg-indigo-600 hover:bg-indigo-500 text-white text-sm font-medium transition-colors disabled:opacity-50"
        >
          {assembling ? 'Retrying…' : 'Retry Assembly'}
        </button>
      </div>
    )
  }

  const tabs = [
    { id: 'code' as const,  label: '💻 Files' },
    { id: 'env'  as const,  label: '🔑 Env Variables' },
    ...(editEnabled ? [{ id: 'edit' as const, label: '✏️ Edit' }] : []),
  ]

  return (
    <div className="h-screen flex flex-col bg-slate-50 text-slate-900 overflow-hidden">

      {/* ── Toolbar ───────────────────────────────────────────────────────── */}
      <header className="flex items-center justify-between px-4 h-12 border-b border-slate-200 shrink-0 bg-white backdrop-blur-sm">
        <div className="flex items-center gap-3">
          <Link href={`/roundtable/${taskId}`} className="text-slate-500 hover:text-slate-700 text-sm transition-colors">
            ← Task
          </Link>
          <div className="h-4 w-px bg-slate-200" />
          <span className="text-sm font-medium text-slate-800 truncate max-w-xs">
            💻 {project.name}
          </span>
          <span className="text-[10px] text-slate-400">
            {project.files.length} file{project.files.length !== 1 ? 's' : ''}
          </span>
        </div>

        <div className="flex items-center gap-2">
          <button
            onClick={downloadZip}
            className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-slate-100 hover:bg-slate-200 text-slate-700 text-xs font-medium transition-colors"
          >
            ⬇ Download ZIP
          </button>

          {project.repoUrl ? (
            <a
              href={project.repoUrl}
              target="_blank"
              rel="noopener noreferrer"
              className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-emerald-50 hover:bg-emerald-100 text-emerald-600 text-xs font-medium transition-colors border border-emerald-200"
            >
              ✓ View on GitHub
            </a>
          ) : ghConn ? (
            <button
              onClick={() => setShowPush(true)}
              className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-slate-100 hover:bg-slate-200 text-slate-700 text-xs font-medium transition-colors"
            >
              Push to GitHub
            </button>
          ) : (
            <a
              href={`/api/v1/github/auth/start`}
              className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-slate-100 hover:bg-slate-200 text-slate-700 text-xs font-medium transition-colors"
            >
              Connect GitHub
            </a>
          )}
        </div>
      </header>

      {/* ── Tab bar ───────────────────────────────────────────────────────── */}
      <div className="flex border-b border-slate-200 shrink-0 bg-white">
        {tabs.map((tab) => (
          <button
            key={tab.id}
            onClick={() => setActiveTab(tab.id)}
            className={`px-4 py-2 text-xs font-medium transition-colors border-b-2 ${
              activeTab === tab.id
                ? 'text-slate-900 border-indigo-500'
                : 'text-slate-500 border-transparent hover:text-slate-700'
            }`}
          >
            {tab.label}
            {tab.id === 'edit' && pendingPlan && (
              <span className="ml-1.5 inline-flex items-center justify-center w-4 h-4 rounded-full bg-indigo-600 text-white text-[9px] font-bold">
                1
              </span>
            )}
          </button>
        ))}
      </div>

      {/* ── Main layout ───────────────────────────────────────────────────── */}
      {activeTab === 'code' && (
        <div className="flex flex-1 min-h-0">
          <aside className="w-56 border-r border-slate-200 bg-slate-100 shrink-0 overflow-hidden">
            <FileTree
              files={project.files}
              selected={selected?.path ?? null}
              onSelect={setSelected}
            />
          </aside>
          <main className="flex-1 min-w-0 bg-slate-50">
            <CodeViewer file={selected} />
          </main>
        </div>
      )}

      {activeTab === 'env' && (
        <div className="flex-1 overflow-y-auto">
          <EnvVarsPanel projectId={project.id} />
        </div>
      )}

      {activeTab === 'edit' && (
        <div className="flex flex-1 min-h-0">
          {/* Chat panel — left column */}
          <div className="flex flex-col w-96 border-r border-slate-200 bg-slate-50 shrink-0 min-h-0">
            {/* Plan card (shown above chat when a plan is ready) */}
            {pendingPlan && (
              <div className="border-b border-slate-200">
                <EditPlanCard
                  taskId={taskId}
                  sessionId={pendingPlan.sessionId}
                  explanation={pendingPlan.explanation}
                  files={pendingPlan.files}
                  onApproved={handleEditPlanApproved}
                  onRejected={handleEditPlanRejected}
                />
              </div>
            )}

            {/* Apply progress */}
            {(isApplying || appliedFiles.length > 0) && (
              <div className="border-b border-slate-200">
                <DiffViewer
                  appliedFiles={appliedFiles}
                  isApplying={isApplying}
                  totalFiles={applyTotal}
                />
              </div>
            )}

            <div className="flex-1 min-h-0 overflow-hidden">
              <EditChatPanel
                taskId={taskId}
                isApplying={isApplying}
                onSessionCreated={(sid) => setActiveSession(sid)}
              />
            </div>
          </div>

          {/* Code viewer — right column (shows updated files) */}
          <div className="flex flex-1 min-h-0 min-w-0">
            <aside className="w-56 border-r border-slate-200 bg-slate-100 shrink-0 overflow-hidden">
              <FileTree
                files={project.files}
                selected={selected?.path ?? null}
                onSelect={setSelected}
              />
            </aside>
            <main className="flex-1 min-w-0 bg-slate-50">
              <CodeViewer file={selected} />
            </main>
          </div>
        </div>
      )}

      {/* ── Push to GitHub modal ──────────────────────────────────────────── */}
      {showPush && (
        <div className="fixed inset-0 bg-slate-900/40 backdrop-blur-sm flex items-center justify-center z-50 p-4">
          <div className="bg-white border border-slate-200 rounded-2xl p-6 w-full max-w-md">
            <h2 className="text-lg font-semibold text-slate-900 mb-1">Push to GitHub</h2>
            <p className="text-sm text-slate-500 mb-5">
              Creates a new public repository and pushes all {project.files.length} files.
              {ghConn && <span className="text-slate-700"> Pushing as <strong>{ghConn.login}</strong>.</span>}
            </p>

            <label className="block text-xs text-slate-500 mb-1.5">Repository name</label>
            <input
              value={repoInput}
              onChange={(e) => setRepoInput(e.target.value)}
              placeholder={project.name.toLowerCase().replace(/[^a-z0-9]/g, '-').replace(/-+/g, '-').slice(0, 40)}
              className="w-full px-3 py-2 rounded-xl bg-slate-100 border border-slate-200 focus:border-indigo-500 focus:outline-none text-sm text-slate-900 placeholder-slate-400 mb-4 transition-colors"
            />

            {pushError && (
              <p className="text-red-600 text-xs mb-3">{pushError}</p>
            )}

            <div className="flex gap-3">
              <button
                onClick={pushToGitHub}
                disabled={pushing}
                className="flex-1 py-2 rounded-xl bg-indigo-600 hover:bg-indigo-500 text-white text-sm font-medium transition-colors disabled:opacity-50"
              >
                {pushing ? 'Pushing…' : 'Push'}
              </button>
              <button
                onClick={() => { setShowPush(false); setPushError('') }}
                className="px-4 py-2 rounded-xl border border-slate-200 hover:border-slate-300 text-slate-500 text-sm transition-colors"
              >
                Cancel
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  )
}
