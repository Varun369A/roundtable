/**
 * GitHub API integration.
 * Creates repos and pushes files using the GitHub REST API.
 * No external SDK — plain fetch calls.
 */

export interface GitHubUser {
  id:        number
  login:     string
  avatarUrl: string
  name?:     string
}

export interface GitHubRepo {
  id:       number
  name:     string
  fullName: string
  htmlUrl:  string
  private:  boolean
}

const GH_API = 'https://api.github.com'

function ghHeaders(token: string) {
  return {
    Authorization:        `Bearer ${token}`,
    Accept:               'application/vnd.github+json',
    'X-GitHub-Api-Version': '2022-11-28',
    'Content-Type':       'application/json',
    'User-Agent':         'Arivarangam-AI/1.0',
  }
}

// ─── Auth ─────────────────────────────────────────────────────────────────────

/** Exchange OAuth code for access token */
export async function exchangeCodeForToken(code: string): Promise<string> {
  const res = await fetch('https://github.com/login/oauth/access_token', {
    method: 'POST',
    headers: { Accept: 'application/json', 'Content-Type': 'application/json' },
    body: JSON.stringify({
      client_id:     process.env.GITHUB_CLIENT_ID,
      client_secret: process.env.GITHUB_CLIENT_SECRET,
      code,
    }),
  })
  const data = await res.json() as any
  if (data.error) throw new Error(`GitHub OAuth error: ${data.error_description}`)
  return data.access_token as string
}

/** Get authenticated GitHub user */
export async function getGitHubUser(token: string): Promise<GitHubUser> {
  const res = await fetch(`${GH_API}/user`, { headers: ghHeaders(token) })
  if (!res.ok) throw new Error(`GitHub user fetch failed: ${res.status}`)
  const u = await res.json() as any
  return { id: u.id, login: u.login, avatarUrl: u.avatar_url, name: u.name }
}

// ─── Repo management ─────────────────────────────────────────────────────────

/** Create a new public or private repo */
export async function createRepo(
  token:   string,
  name:    string,
  opts:    { description?: string; isPrivate?: boolean } = {}
): Promise<GitHubRepo> {
  const res = await fetch(`${GH_API}/user/repos`, {
    method:  'POST',
    headers: ghHeaders(token),
    body: JSON.stringify({
      name,
      description: opts.description ?? 'Generated by Arivarangam',
      private:     opts.isPrivate ?? false,
      auto_init:   false,
    }),
  })
  if (!res.ok) {
    const err = await res.json() as any
    throw new Error(err.message ?? `Failed to create repo: ${res.status}`)
  }
  const r = await res.json() as any
  return { id: r.id, name: r.name, fullName: r.full_name, htmlUrl: r.html_url, private: r.private }
}

/** Push a batch of files to a repo using the Git Trees API (efficient, single commit) */
export async function pushFiles(
  token:   string,
  owner:   string,
  repo:    string,
  files:   Array<{ path: string; content: string }>,
  message: string = 'Initial commit by Arivarangam'
): Promise<string> {
  // 1. Get HEAD ref (or create empty tree if new repo)
  let baseSha: string | null = null
  let baseTree: string | null = null

  try {
    const refRes = await fetch(`${GH_API}/repos/${owner}/${repo}/git/ref/heads/main`, {
      headers: ghHeaders(token),
    })
    if (refRes.ok) {
      const ref = await refRes.json() as any
      baseSha  = ref.object.sha
      const commitRes = await fetch(`${GH_API}/repos/${owner}/${repo}/git/commits/${baseSha}`, {
        headers: ghHeaders(token),
      })
      const commit = await commitRes.json() as any
      baseTree = commit.tree.sha
    }
  } catch {
    // new repo, no commits yet
  }

  // 2. Create blobs for each file
  const treeItems: any[] = []
  for (const file of files) {
    const blobRes = await fetch(`${GH_API}/repos/${owner}/${repo}/git/blobs`, {
      method:  'POST',
      headers: ghHeaders(token),
      body:    JSON.stringify({ content: file.content, encoding: 'utf-8' }),
    })
    if (!blobRes.ok) {
      const err = await blobRes.json() as any
      throw new Error(`Failed to create blob for ${file.path}: ${err.message}`)
    }
    const blob = await blobRes.json() as any
    treeItems.push({ path: file.path, mode: '100644', type: 'blob', sha: blob.sha })
  }

  // 3. Create tree
  const treeBody: any = { tree: treeItems }
  if (baseTree) treeBody.base_tree = baseTree

  const treeRes = await fetch(`${GH_API}/repos/${owner}/${repo}/git/trees`, {
    method:  'POST',
    headers: ghHeaders(token),
    body:    JSON.stringify(treeBody),
  })
  if (!treeRes.ok) {
    const err = await treeRes.json() as any
    throw new Error(`Failed to create tree: ${err.message}`)
  }
  const tree = await treeRes.json() as any

  // 4. Create commit
  const commitBody: any = {
    message,
    tree: tree.sha,
    author: { name: 'Arivarangam', email: 'ai@arivarangam.com', date: new Date().toISOString() },
  }
  if (baseSha) commitBody.parents = [baseSha]

  const commitRes = await fetch(`${GH_API}/repos/${owner}/${repo}/git/commits`, {
    method:  'POST',
    headers: ghHeaders(token),
    body:    JSON.stringify(commitBody),
  })
  if (!commitRes.ok) {
    const err = await commitRes.json() as any
    throw new Error(`Failed to create commit: ${err.message}`)
  }
  const commit = await commitRes.json() as any

  // 5. Update (or create) the main ref
  const updateRef = await fetch(`${GH_API}/repos/${owner}/${repo}/git/refs/heads/main`, {
    method:  'PATCH',
    headers: ghHeaders(token),
    body:    JSON.stringify({ sha: commit.sha, force: false }),
  })

  if (!updateRef.ok) {
    // Ref doesn't exist yet — create it
    await fetch(`${GH_API}/repos/${owner}/${repo}/git/refs`, {
      method:  'POST',
      headers: ghHeaders(token),
      body:    JSON.stringify({ ref: 'refs/heads/main', sha: commit.sha }),
    })
  }

  return `https://github.com/${owner}/${repo}`
}

/** Sanitize a string into a valid GitHub repo name */
export function toRepoName(title: string): string {
  return title
    .toLowerCase()
    .replace(/[^a-z0-9\-_]/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 100) || 'sabha-project'
}
