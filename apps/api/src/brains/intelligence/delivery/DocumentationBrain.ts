/**
 * DocumentationBrain — Generates README and API docs from code analysis.
 * Zero API — template + AST parsing.
 */

import { Brain, BrainContext } from '../../base/Brain'
import type { GeneratedFile } from '../../build/implementation/FileGeneratorBrain'
import type { APIEndpoint } from '../../build/architecture/APIBrain'

export interface DocumentationBrainInput {
  generatedFiles: GeneratedFile[]
  goal: string
  mainTechStack: string[]
  endpoints: APIEndpoint[]
  envVariables: string[]
  packageJsonScripts: Record<string, string>
}

export interface DocumentationBrainOutput {
  readmeFile: GeneratedFile
  apiDocsFile: GeneratedFile | null
}

export class DocumentationBrain extends Brain<DocumentationBrainInput, DocumentationBrainOutput> {
  readonly brainName = 'DocumentationBrain'
  readonly orchestratorName = 'DeliveryOrchestrator'
  readonly engineName = 'IntelligenceEngine'
  readonly usesAI = false

  protected async process(input: DocumentationBrainInput, _ctx: BrainContext): Promise<DocumentationBrainOutput> {
    const { goal, mainTechStack, endpoints, envVariables, packageJsonScripts, generatedFiles } = input

    // README
    const readmeLines = [
      `# ${this.extractAppName(goal)}`,
      ``,
      `> ${goal.slice(0, 120)}`,
      ``,
      `## Tech Stack`,
      ``,
      mainTechStack.map(t => `- ${t}`).join('\n'),
      ``,
      `## Getting Started`,
      ``,
      `### Prerequisites`,
      `- Node.js 18+`,
      `- PostgreSQL (or see .env.example for alternatives)`,
      ``,
      `### Installation`,
      ``,
      `\`\`\`bash`,
      `git clone <your-repo>`,
      `cd <project-name>`,
      `npm install`,
      `\`\`\``,
      ``,
      `### Environment Variables`,
      ``,
      `Copy \`.env.example\` to \`.env\` and fill in your values:`,
      ``,
      `\`\`\`bash`,
      `cp .env.example .env`,
      `\`\`\``,
      ``,
      envVariables.length > 0 ? `Required variables:\n${envVariables.map(v => `- \`${v}\``).join('\n')}` : '',
      ``,
      `### Running the App`,
      ``,
      `\`\`\`bash`,
      Object.entries(packageJsonScripts).map(([k, v]) => `# ${k}\nnpm run ${k}`).join('\n\n'),
      `\`\`\``,
      ``,
      endpoints.length > 0 ? `## API Reference\n\nSee [API.md](./API.md) for full endpoint documentation.\n` : '',
      `## Project Structure`,
      ``,
      `\`\`\``,
      generatedFiles.slice(0, 15).map(f => f.path).join('\n'),
      `\`\`\``,
      ``,
      `---`,
      `*Generated by Arivarangam AI*`,
    ]

    const readmeContent = readmeLines.filter(l => l !== null && l !== undefined).join('\n')
    const readmeFile: GeneratedFile = {
      path: 'README.md',
      content: readmeContent,
      language: 'markdown',
      linesOfCode: readmeContent.split('\n').length,
      purpose: 'Project README with setup instructions',
    }

    // API docs
    let apiDocsFile: GeneratedFile | null = null
    if (endpoints.length > 0) {
      const apiLines = [
        `# API Documentation`,
        ``,
        `Base URL: \`/api/v1\``,
        ``,
        `## Authentication`,
        ``,
        `Include JWT token in the Authorization header:`,
        `\`\`\``,
        `Authorization: Bearer <your-token>`,
        `\`\`\``,
        ``,
        `## Endpoints`,
        ``,
        ...endpoints.map(ep => [
          `### ${ep.method} ${ep.path}`,
          ``,
          `**Description:** ${ep.description}`,
          `**Auth Required:** ${ep.requiresAuth ? 'Yes' : 'No'}`,
          ep.requestBody ? `**Request Body:** \`${ep.requestBody}\`` : '',
          `**Response:** \`${ep.responseType}\``,
          ``,
        ].join('\n')),
      ]
      const apiContent = apiLines.join('\n')
      apiDocsFile = { path: 'API.md', content: apiContent, language: 'markdown', linesOfCode: apiContent.split('\n').length, purpose: 'API endpoint documentation' }
    }

    return { readmeFile, apiDocsFile }
  }

  private extractAppName(goal: string): string {
    const words = goal.split(/\s+/).slice(0, 5)
    return words.map(w => w.charAt(0).toUpperCase() + w.slice(1)).join(' ')
  }

  protected fallback(input: DocumentationBrainInput): DocumentationBrainOutput {
    return {
      readmeFile: { path: 'README.md', content: `# App\n\n${input.goal}\n`, language: 'markdown', linesOfCode: 3, purpose: 'README' },
      apiDocsFile: null,
    }
  }
}
